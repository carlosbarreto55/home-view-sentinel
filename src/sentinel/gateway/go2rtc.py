"""Render go2rtc's configuration from sentinel.yaml.

The file has no secrets: stream sources use ``${DVR_USER}`` and ``${DVR_PASSWORD}``,
which go2rtc expands from its environment. The launcher passes the Keychain values,
percent-encoded, only to the go2rtc process (see ``environment``).
"""

from __future__ import annotations

from pathlib import Path

import yaml

from sentinel.config import Config
from sentinel.rtsp_probe import encode_credential, stream_path

RTSP_PORT = 8554
# Inside the container go2rtc listens on every interface of the container; the
# port is published on the Mac's 127.0.0.1 only.
CONTAINER_RTSP_LISTEN = f":{RTSP_PORT}"


def source_url(config: Config, channel: int, subtype: int) -> str:
    """The DVR stream address with credential placeholders (expanded by go2rtc)."""
    return (
        f"rtsp://${{DVR_USER}}:${{DVR_PASSWORD}}@{config.dvr.host}:{config.dvr.port}"
        f"{stream_path(channel, subtype)}"
    )


def local_url(camera_id: str, host: str = "127.0.0.1", port: int = RTSP_PORT) -> str:
    """Where the other components read a camera from the gateway."""
    return f"rtsp://{host}:{port}/{camera_id}"


def render(config: Config, rtsp_listen: str = CONTAINER_RTSP_LISTEN) -> str:
    """go2rtc.yaml for the configured cameras only, with every other server off."""
    document = {
        "log": {"level": "info"},
        # An empty listen address turns a server off: no HTTP API or web UI,
        # no WebRTC, RTMP or SRTP. Only the RTSP restreams are served.
        "api": {"listen": ""},
        "webrtc": {"listen": ""},
        "rtmp": {"listen": ""},
        "srtp": {"listen": ""},
        "rtsp": {"listen": rtsp_listen},
        "streams": {
            camera.id: source_url(config, camera.channel, camera.subtype)
            for camera in config.cameras
        },
    }
    header = "# Generated by HomeView Sentinel from config/sentinel.yaml. Do not edit.\n"
    return header + yaml.safe_dump(document, sort_keys=False, allow_unicode=True)


def write(config: Config, path: Path, rtsp_listen: str = CONTAINER_RTSP_LISTEN) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render(config, rtsp_listen), encoding="utf-8")
    return path


def environment(user: str, password: str) -> dict[str, str]:
    """The go2rtc process environment for the DVR login, percent-encoded for the URL."""
    return {"DVR_USER": encode_credential(user), "DVR_PASSWORD": encode_credential(password)}
