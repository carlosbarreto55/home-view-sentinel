"""The broker launcher: Mosquitto in a container, users from the Keychain.

``python -m sentinel.bus.broker`` (run by launchd) writes, into Application
Support, a ``mosquitto.conf`` (one listener, anonymous refused, persistence on)
and a password file with one user per component, hashed the way
``mosquitto_passwd`` does (PBKDF2-SHA512, ``$7$``), so no broker password is
ever on disk in clear. Then it runs Mosquitto with the port published on the
Mac's loopback only.
"""

from __future__ import annotations

import base64
import hashlib
import logging
import os
import secrets as random
import sys
from collections.abc import Callable, Mapping
from pathlib import Path

from sentinel import paths, secrets
from sentinel.runtime import EXIT_DONE, EXIT_RESTART, container, logs

log = logging.getLogger("sentinel.broker")

IMAGE = "docker.io/library/eclipse-mosquitto:2.0.22"
CONTAINER_NAME = "sentinel-broker"
PORT = 1883
ITERATIONS = 101  # mosquitto_passwd's default for $7$

CONFIG = """\
# Generated by HomeView Sentinel at start. Do not edit.
listener 1883
allow_anonymous false
password_file /mosquitto/config/passwd
persistence true
persistence_location /mosquitto/data/
autosave_interval 60
log_dest stderr
log_timestamp false
log_type error
log_type warning
log_type notice
"""


def password_hash(password: str, salt: bytes | None = None) -> str:
    """A Mosquitto 2 ``$7$`` hash: PBKDF2-SHA512, 101 iterations, 12-byte salt."""
    salt = salt if salt is not None else random.token_bytes(12)
    digest = hashlib.pbkdf2_hmac("sha512", password.encode(), salt, ITERATIONS, 64)
    encode = base64.b64encode
    return f"$7${ITERATIONS}${encode(salt).decode()}${encode(digest).decode()}"


def password_file(passwords: Mapping[str, str]) -> str:
    return "".join(f"{user}:{password_hash(pw)}\n" for user, pw in passwords.items())


def write_config(directory: Path, passwords: Mapping[str, str]) -> None:
    """mosquitto.conf and the hashed password file (owner-only)."""
    directory.mkdir(parents=True, exist_ok=True)
    (directory / "mosquitto.conf").write_text(CONFIG, encoding="utf-8")
    passwd = directory / "passwd"
    temporary = passwd.with_suffix(".tmp")
    fd = os.open(temporary, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as file:
        file.write(password_file(passwords))
    os.replace(temporary, passwd)


def container_spec(directory: Path) -> container.ContainerSpec:
    return container.ContainerSpec(
        name=CONTAINER_NAME,
        image=IMAGE,
        # Skip the image's entrypoint script, which tries to chown the mounts.
        extra=("--entrypoint", "mosquitto"),
        command=("-c", "/mosquitto/config/mosquitto.conf"),
        publish=(f"127.0.0.1:{PORT}:{PORT}",),
        mounts=(
            (directory / "config", "/mosquitto/config"),
            (directory / "data", "/mosquitto/data"),
        ),
        cpus=1,
        memory="256M",  # container 1.5 refuses less than 200 MiB
    )


def run(
    directory: Path,
    read_secret: Callable[[str], str | None] = secrets.get,
    run_container: Callable[..., container.RunResult] = container.run,
    wait_for_system: Callable[[], bool] = container.wait_for_system,
) -> int:
    passwords = {user: read_secret(secrets.mqtt_item(user)) for user in secrets.MQTT_USERS}
    missing = [secrets.mqtt_item(user) for user, pw in passwords.items() if not pw]
    if missing:
        log.error("%s not in the Keychain; run `make secrets`", ", ".join(missing))
        return EXIT_DONE
    if not wait_for_system():
        log.error("the container system is not running; launchd will try again")
        return EXIT_RESTART
    write_config(directory / "config", passwords)
    (directory / "data").mkdir(parents=True, exist_ok=True)
    log.info("starting Mosquitto on 127.0.0.1:%d for %s", PORT, ", ".join(passwords))
    outcome = run_container(
        container_spec(directory), on_line=lambda line: log.info("mosquitto: %s", line)
    )
    return EXIT_DONE if outcome.stopped else EXIT_RESTART


def main() -> int:
    logs.setup("broker")
    try:
        return run(paths.broker_dir())
    except secrets.KeychainError as error:
        log.error("%s", error)
        return EXIT_RESTART


if __name__ == "__main__":
    sys.exit(main())
